/** Tone marks used in Zhuyin IME. */
export const ZHUYIN_TONES = ['ˊ', 'ˇ', 'ˋ', '˙'] as const;

/** Strip tone marks from a zhuyin string. */
export function stripTone(s: string) {
  return s.replace(/[ˊˇˋ˙]/g, '');
}

export function endsWithTone(s: string) {
  return /[ˊˇˋ˙]$/.test(s);
}

